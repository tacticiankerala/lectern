/// The Markdown extensions, for the UI's file picker, written next to the ts-rs bindings so the
/// list lives in one place. Written only when it changed, so the file keeps its timestamp.
#[test]
fn markdown_extensions_exported() {
    let list = MARKDOWN_EXTENSIONS
        .iter()
        .map(|ext| format!("\"{ext}\""))
        .collect::<Vec<_>>()
        .join(", ");
    let ts = format!(
        "// Generated from `lectern_core::library::MARKDOWN_EXTENSIONS` by `cargo test -p lectern-core`. Do not edit this file manually.\n\n\
         /** The extensions of the files Lectern treats as Markdown notes. */\n\
         export const MARKDOWN_EXTENSIONS: readonly string[] = [{list}];\n"
    );
    let path = generated_dir().join("markdown-extensions.ts");
    if fs::read_to_string(&path).ok().as_deref() != Some(ts.as_str()) {
        fs::write(&path, &ts).unwrap();
    }
    assert!(ts.contains(r#"["md", "markdown", "mdown", "mkd"]"#), "{ts}");
}

