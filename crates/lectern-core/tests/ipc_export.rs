/// Every key Rust names while the focus is inside a frame, with the modifiers it is one of
/// Lectern's shortcuts with (`frame_keys`), for the UI's test against `keymap.ts`.
#[test]
fn frame_keys_exported() {
    let quote = |s: &str| serde_json::to_string(s).unwrap();
    let rows = keys()
        .iter()
        .map(|k| {
            let lectern = k
                .lectern
                .iter()
                .map(|m| quote(m))
                .collect::<Vec<_>>()
                .join(", ");
            format!(
                "  {{ key: {}, shifted: {}, code: {}, lectern: [{lectern}] }},",
                quote(&k.key),
                quote(&k.shifted),
                quote(&k.code)
            )
        })
        .collect::<Vec<_>>()
        .join("\n");
    let ts = format!(
        "// Generated from `lectern_core::frame_keys` by `cargo test -p lectern-core`. Do not edit this file manually.\n\n\
         /**\n * Every key Rust names while the focus is inside a frame: its `key` without and with Shift, its\n \
         * `code`, and the modifiers (\"plain\", \"Shift\", \"Ctrl\", \"Ctrl+Shift\", \"Alt\", \"Alt+Shift\",\n \
         * \"Ctrl+Alt\", \"Ctrl+Alt+Shift\") it is one of Lectern's shortcuts with, so Rust handles it.\n \
         */\n\
         export const FRAME_KEYS: readonly {{\n  key: string;\n  shifted: string;\n  code: string;\n  lectern: readonly string[];\n}}[] = [\n{rows}\n];\n"
    );
    let path = generated_dir().join("frame-keys.ts");
    if fs::read_to_string(&path).ok().as_deref() != Some(ts.as_str()) {
        fs::write(&path, &ts).unwrap();
    }
    assert!(
        ts.contains(
            r#"{ key: "o", shifted: "O", code: "KeyO", lectern: ["Ctrl", "Ctrl+Shift"] },"#
        ),
        "{ts}"
    );
}

/// Pages as Lectern serves them, for the UI's test that the fake's dev server (`ui/dev/`) serves
/// them the same: each mode's policies, where the bridge goes in pages made to trip it up, the
/// charset each page made to trip up the prescan is served with, and which files beside a page it
/// may read.
#[test]
fn page_vectors_exported() {
    // JSON, with the byte order mark spelled out rather than invisible.
    let quote = |s: &str| {
        serde_json::to_string(s)
            .unwrap()
            .replace('\u{feff}', "\\ufeff")
    };
    let policies = [
        ("full", HtmlPages::Full),
        ("offline", HtmlPages::Offline),
        ("static", HtmlPages::Static),
    ]
    .iter()
    .flat_map(|&(name, mode)| {
        [Some("TOKEN"), None].into_iter().map(move |report| {
            let policy = page_policy(mode, "NONCE", report);
            format!(
                "  {{ mode: {}, token: {}, enforced: {}, reportOnly: {} }},",
                quote(name),
                report.map_or("null".to_owned(), quote),
                quote(&policy.enforced),
                policy
                    .report_only
                    .as_deref()
                    .map_or("null".to_owned(), quote)
            )
        })
    })
    .collect::<Vec<_>>()
    .join("\n");
    let script = r#"<script nonce="NONCE">BRIDGE</script>"#;
    let pages = [
        r#"<!doctype html><html lang="en"><head><title>T</title></head><body>x</body>"#,
        "\u{feff}<!DOCTYPE html>\n<!-- <head> -->\n<HTML>\n  <HEAD data-x=\"a>b\" >\n<meta charset=\"utf-8\">",
        "<html><header>x</header>",
        "<!doctype html><html><body><p>Hi</p>",
        "<!doctype html>\n<p>Hi</p>",
        "<p>Hi</p>",
        "",
        "\u{feff}<p>Hi</p>",
        "<html><body><script>document.write('<head>')</script>",
        "Hello <head>",
        "<!--><script>x()</script><!-- --><head>",
        "<!---><script>x()</script><!-- --><head>",
        "<!----><head>",
        "<!-- a --!><head><title>T</title>",
        "<!-- a --!><script>x()</script><head>",
        "<!-- unclosed <head>",
        r#"<head a"><p title=">"#,
        r#"<html a"><script>x()</script><head b="1">"#,
        "<html lang = 'e>n' data-x=a>b><head>",
        r#"<head ="><script>x()</script><p title="a">"#,
        r#"<head x='1'y="2"/><title>"#,
        r#"<?xml version="1.0"?><html><head>"#,
        "<head",
        "<html/><head/>",
        "</p><head>",
        "<!DOCTYPE html><!-- c --><html><!-- d --><head>",
    ];
    let injections = pages
        .iter()
        .map(|page| {
            let out = String::from_utf8(inject_script(page.as_bytes(), script)).unwrap();
            format!("  {{ page: {}, injected: {} }},", quote(page), quote(&out))
        })
        .collect::<Vec<_>>()
        .join("\n");
    // Bytes, a character each, anything past ASCII spelled out.
    let bytes = |page: &[u8]| {
        let text: String = page.iter().map(|&b| char::from(b)).collect();
        serde_json::to_string(&text)
            .unwrap()
            .chars()
            .map(|c| {
                if c.is_ascii() {
                    c.to_string()
                } else {
                    format!("\\u{:04x}", u32::from(c))
                }
            })
            .collect::<String>()
    };
    let mut late = vec![b' '; 1024];
    late.extend_from_slice(b"<meta charset=\"koi8-r\">");
    let charset_pages: Vec<&[u8]> = vec![
        b"<!doctype html><html><head><meta charset=\"UTF-8\"><title>x",
        b"<head><META http-equiv=\"Content-Type\" content=\"text/html; charset=windows-1252\">",
        b"<meta charset=shift_jis>",
        b"<meta/charset=big5>",
        b"<meta charset=\"koi8-r\" charset=\"utf-8\">",
        b"<meta charset=\"\">",
        b"<meta charset=\"no such label!\">",
        b"<!-- <meta charset=\"shift_jis\"> --><meta charset=\"utf-8\">",
        b"<!--><meta charset=\"koi8-r\">",
        b"<!---><meta charset=\"koi8-r\">",
        b"<!-- unclosed <meta charset=\"koi8-r\">",
        b"<meta content=\"text/html; charset=windows-1252\">",
        b"<meta http-equiv=\"refresh\" content=\"0; charset=koi8-r\">",
        b"<meta content='text/html; charset=\"iso-8859-2\"' http-equiv=Content-Type>",
        b"<meta http-equiv=content-type content=\"text/html;charset = gbk ;x\">",
        b"<p title='<meta charset=koi8-r>'><meta charset=utf-8>",
        b"<?xml version=\"1.0\"?><meta charset=euc-kr>",
        b"<metal charset=koi8-r>",
        b"<meta charset=\"UTF-16LE\">",
        b"<meta charset=\"windows-1252\"><p>Hi</p>",
        b"<html><head><meta charset=\"windows-1252\"><title>Caf\xe9",
        "<title>Tide notes · “Spring” week</title>".as_bytes(),
        b"<p>Hi</p>",
        b"",
        &late,
        b"<title>Caf\xe9</title>",
        b"\xEF\xBB\xBF<p>Hi</p>",
        b"\xFF\xFE<\0p\0>\0",
        b"\xFE\xFF\0<\0p\0>",
    ];
    let charsets = charset_pages
        .iter()
        .map(|page| {
            let charset = prepare_page(page, None).charset;
            format!(
                "  {{ page: {}, charset: {} }},",
                bytes(page),
                charset.as_deref().map_or("null".to_owned(), quote)
            )
        })
        .collect::<Vec<_>>()
        .join("\n");
    let shared = SHARED_EXTENSIONS
        .iter()
        .map(|ext| quote(ext))
        .collect::<Vec<_>>()
        .join(", ");
    let ts = format!(
        "// Generated from `lectern_core::page` by `cargo test -p lectern-core`. Do not edit this file manually.\n\n\
         /** The policies `page_policy` gives each mode for the nonce `NONCE`, with the open `TOKEN` and with none. */\n\
         export const PAGE_POLICIES: readonly {{\n  mode: string;\n  token: string | null;\n  enforced: string;\n  reportOnly: string | null;\n}}[] = [\n{policies}\n];\n\n\
         /** Where `inject_script` puts `<script nonce=\"NONCE\">BRIDGE</script>` in each page. */\n\
         export const INJECTIONS: readonly {{ page: string; injected: string }}[] = [\n{injections}\n];\n\n\
         /** The charset `prepare_page` serves each page with, its bytes a character each. */\n\
         export const CHARSETS: readonly {{ page: string; charset: string | null }}[] = [\n{charsets}\n];\n\n\
         /** Where the bridge takes its open's key (`BRIDGE_KEY_SLOT`). */\n\
         export const BRIDGE_KEY_SLOT = {};\n\n\
         /** The extensions of the files beside a page it may read (`SHARED_EXTENSIONS`): its scripts and fonts. */\n\
         export const SHARED_EXTENSIONS: readonly string[] = [{shared}];\n",
        quote(BRIDGE_KEY_SLOT)
    );
    let path = generated_dir().join("page-vectors.ts");
    if fs::read_to_string(&path).ok().as_deref() != Some(ts.as_str()) {
        fs::write(&path, &ts).unwrap();
    }
    assert!(ts.contains(
        r#"{ page: "<!--><script>x()</script><!-- --><head>", injected: "<script nonce=\"NONCE\">BRIDGE</script><!--><script>x()</script><!-- --><head>" },"#
    ), "{ts}");
    assert!(
        ts.contains(r#"SHARED_EXTENSIONS: readonly string[] = ["js", "mjs", "woff", "woff2", "ttf", "otf"];"#),
        "{ts}"
    );
    assert!(
        ts.contains(r#"{ page: "<title>Caf\u00e9</title>", charset: null },"#),
        "{ts}"
    );
}

