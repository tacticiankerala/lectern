/// An agent's `show` held for a window still starting comes with its target, which the UI applies
/// once the file has opened; a payload without one leaves it out.
#[test]
fn startup_payload_carries_an_agents_target() {
    let payload = |agent_target| StartupPayload {
        settings: Default::default(),
        settings_rev: 0,
        library: lectern_core::ipc::LibraryPayload { roots: vec![] },
        recent: vec![],
        initial: None,
        version: "0.5.0".to_owned(),
        portable: false,
        startup_notice: None,
        workspace: None,
        workspaces: vec![],
        primary: false,
        generation: 0,
        agent_target,
    };
    let held = ShowAt {
        target: Target::Heading {
            heading: "Rollout".to_owned(),
        },
        place: Some(TextPlace {
            start_line: 5,
            end_line: 5,
            text_start: Some(17),
            text_end: Some(24),
            block_offset: None,
        }),
    };
    let j = serde_json::to_value(payload(Some(held))).unwrap();
    assert_eq!(
        j["agentTarget"],
        json!({
            "target": {"heading": "Rollout"},
            "place": {"startLine": 5, "endLine": 5, "textStart": 17, "textEnd": 24},
        })
    );
    let j = serde_json::to_value(payload(None)).unwrap();
    assert!(j.get("agentTarget").is_none());
    assert!(decl::<StartupPayload>().contains("agentTarget?: ShowAt"));
}

#[test]
fn startup_payload_names_the_window_workspace() {
    let personal = WorkspaceSummary {
        id: "w2".to_owned(),
        name: "Personal".to_owned(),
        open: true,
        current: true,
        roots: vec!["C:\\Users\\me\\projects".to_owned()],
        own_theme: true,
    };
    let work = WorkspaceSummary {
        id: "w1".to_owned(),
        name: "Work".to_owned(),
        open: false,
        current: false,
        roots: vec![],
        own_theme: false,
    };
    let j = serde_json::to_value(StartupPayload {
        settings: Default::default(),
        settings_rev: 0,
        library: lectern_core::ipc::LibraryPayload { roots: vec![] },
        recent: vec![],
        initial: None,
        version: "0.3.0".to_owned(),
        portable: false,
        startup_notice: None,
        workspace: Some(personal.clone()),
        workspaces: vec![work, personal],
        primary: false,
        generation: 0,
        agent_target: None,
    })
    .unwrap();
    let personal = json!({"id": "w2", "name": "Personal", "open": true, "current": true, "roots": ["C:\\Users\\me\\projects"], "ownTheme": true});
    assert_eq!(j["workspace"], personal);
    // Every workspace, for the title before the first paint.
    assert_eq!(j["workspaces"][1], personal);
    assert_eq!(j["workspaces"][0]["name"], "Work");
    assert!(decl::<StartupPayload>().contains("workspaces: Array<WorkspaceSummary>,"));
    assert_eq!(j["primary"], false);
    assert_eq!(
        serde_json::to_value(OpenWhere::NewWindow).unwrap(),
        json!("newWindow")
    );
    assert_eq!(
        serde_json::from_value::<WorkspaceOutcome>(json!("focused")).unwrap(),
        WorkspaceOutcome::Focused
    );
}
