#[test]
fn review_ops_are_tagged_by_op() {
    let op: ReviewOp =
        serde_json::from_value(json!({"op": "setStatus", "id": 3, "change": "resolve"})).unwrap();
    assert_eq!(
        op,
        ReviewOp::SetStatus {
            id: 3,
            change: StatusChange::Resolve
        }
    );
    let add = ReviewOp::Add {
        anchor: NewAnchor {
            start_line: 4,
            end_line: 6,
            quote: "batches of at most 50".to_owned(),
            prefix: String::new(),
            text_start: None,
        },
        text: "Why 50?".to_owned(),
        author: None,
    };
    assert_eq!(
        serde_json::to_value(&add).unwrap(),
        json!({"op": "add", "anchor": {"startLine": 4, "endLine": 6, "quote": "batches of at most 50", "prefix": ""}, "text": "Why 50?"})
    );
    // An anchor sent without a prefix has an empty one.
    let without: ReviewOp = serde_json::from_value(
        json!({"op": "add", "anchor": {"startLine": 4, "endLine": 6, "quote": "batches of at most 50"}, "text": "Why 50?"}),
    )
    .unwrap();
    assert_eq!(without, add);
    // An agent's, written under its name: the UI sends it for a page.
    let agents: ReviewOp = serde_json::from_value(json!({
        "op": "reply",
        "id": 2,
        "text": "Per station.",
        "author": {"name": "Claude", "kind": "reply"},
    }))
    .unwrap();
    assert_eq!(
        agents,
        ReviewOp::Reply {
            id: 2,
            text: "Per station.".to_owned(),
            author: Some(AgentAuthor {
                name: "Claude".to_owned(),
                kind: ClaudeKind::Reply,
            }),
        }
    );
    assert_eq!(
        decl::<AgentAuthor>(),
        "type AgentAuthor = { name: string, kind: ClaudeKind, };"
    );
    // The comment an operation changed rides on its answer, for the agent a page's window adds it
    // for.
    let payload = decl::<ReviewPayload>();
    assert!(payload.contains("changed?: number, "), "{payload}");
}

